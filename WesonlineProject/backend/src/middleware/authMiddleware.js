import jwt from 'jsonwebtoken';

import Admin from '../models/admin.js';
import GroupReport from '../models/groupReport.js';

/*
|--------------------------------------------------------------------------
| PROTECT ADMIN ROUTES
|--------------------------------------------------------------------------
| Expects:
| Authorization: Bearer <admin-token>
*/

export const protectAdmin = async (req, res, next) => {
  try {
    const authorization = req.headers.authorization;

    if (!authorization || !authorization.startsWith('Bearer ')) {
      return res.status(401).json({
        success: false,
        message: 'Not authorized. Please log in as an administrator.',
      });
    }

    const token = authorization.slice(7).trim();

    if (!token) {
      return res.status(401).json({
        success: false,
        message: 'Authentication token is missing.',
      });
    }

    if (!process.env.JWT_SECRET) {
      console.error('JWT_SECRET is missing from the environment.');

      return res.status(500).json({
        success: false,
        message: 'Authentication service is not configured.',
      });
    }

    let decoded;

    try {
      decoded = jwt.verify(token, process.env.JWT_SECRET);
    } catch (error) {
      return res.status(401).json({
        success: false,
        message:
          error.name === 'TokenExpiredError'
            ? 'Your session has expired. Please log in again.'
            : 'Invalid authentication token. Please log in again.',
      });
    }

    // Only administrator tokens may access administrator routes.
    if (decoded.role !== 'admin' || !decoded.id) {
      return res.status(403).json({
        success: false,
        message:
          'Access denied. Administrator privileges are required.',
      });
    }

    const admin = await Admin.findById(decoded.id);

    if (!admin || !admin.isAdmin || !admin.isEmailVerified) {
      return res.status(401).json({
        success: false,
        message:
          'Your administrator account is invalid or your email is not verified.',
      });
    }

    req.admin = admin;

    next();
  } catch (error) {
    next(error);
  }
};

/*
|--------------------------------------------------------------------------
| PROTECT GROUP LEAD ROUTES
|--------------------------------------------------------------------------
| Expects:
| Authorization: Bearer <group-token>
|
| The token must be generated by loginGroup.
*/

export const protectGroupLead = async (req, res, next) => {
  try {
    const authorization = req.headers.authorization;

    // Check the Authorization header.
    if (!authorization || !authorization.startsWith('Bearer ')) {
      return res.status(401).json({
        success: false,
        message:
          'Not authorized. Please log in to your group account.',
      });
    }

    const token = authorization.slice(7).trim();

    if (!token) {
      return res.status(401).json({
        success: false,
        message: 'Authentication token is missing.',
      });
    }

    // Ensure JWT_SECRET is configured.
    if (!process.env.JWT_SECRET) {
      console.error('JWT_SECRET is missing from the environment.');

      return res.status(500).json({
        success: false,
        message: 'Authentication service is not configured.',
      });
    }

    // Verify the JWT.
    let decoded;

    try {
      decoded = jwt.verify(token, process.env.JWT_SECRET);
    } catch (error) {
      return res.status(401).json({
        success: false,
        message:
          error.name === 'TokenExpiredError'
            ? 'Your session has expired. Please log in again.'
            : 'Invalid authentication token. Please log in again.',
      });
    }

    // Ensure this is a group token, not an administrator token.
    if (
      decoded.role !== 'learner' ||
      !decoded.id ||
      !decoded.groupId
    ) {
      return res.status(403).json({
        success: false,
        message: 'Access denied. A valid group account is required.',
      });
    }

    // Find the group account associated with the token.
    const group = await GroupReport.findById(decoded.id);

    if (!group || !group.isEmailVerified) {
      return res.status(401).json({
        success: false,
        message:
          'Invalid group account or group email has not been verified.',
      });
    }

    // Ensure the group ID in the token matches the database record.
    const tokenGroupId = String(decoded.groupId)
      .trim()
      .toUpperCase()
      .replace(/\s+/g, '');

    const databaseGroupId = String(group.groupId)
      .trim()
      .toUpperCase()
      .replace(/\s+/g, '');

    if (tokenGroupId !== databaseGroupId) {
      return res.status(401).json({
        success: false,
        message: 'Invalid group authentication token.',
      });
    }

    // Attach the authenticated group to the request.
    req.group = group;

    next();
  } catch (error) {
    next(error);
  }
};